def weighted_fortune(rng) -> tuple[str, str, str]:
    levels = [(zh, alias, color, w) for zh, alias, w, color in FORTUNE_LEVELS]
    total = sum(item[3] for item in levels)
    pick = rng.uniform(0, total)
    acc = 0.0
    for zh, alias, color, weight in levels:
        acc += weight
        if pick <= acc:
            return zh, alias, color
    zh, alias, color, _ = levels[2]
    return zh, alias, color


def all_guide_characters() -> list[str]:
    return [XIAO_AI_NAME, *CHARACTER_QUOTES.keys(), *[n for n, _ in OTHER_CHARACTER_GUIDES]]


def pick_character_guide(
    rng,
    character_weights: dict[str, float] | None = None,
) -> tuple[str, str]:
    """按各角色权重抽取共鸣指引。

    character_weights: {角色名: 权重}，0 或缺失视为不参与；未传则默认小爱80、其余1。
    权重在池内归一化后抽取；池为空时回退小爱。
    """
    pool: list[tuple[str, float, list[str]]] = []

    if character_weights:
        # 小爱
        w_ai = float(character_weights.get(XIAO_AI_NAME, 0) or 0)
        if w_ai > 0:
            pool.append((XIAO_AI_NAME, w_ai, XIAO_AI_QUOTES))
        for name, quotes in CHARACTER_QUOTES.items():
            w = float(character_weights.get(name, 0) or 0)
            if w > 0:
                pool.append((name, w, quotes))
        for name, quote in OTHER_CHARACTER_GUIDES:
            w = float(character_weights.get(name, 0) or 0)
            if w > 0:
                pool.append((name, w, [quote]))
    else:
        pool.append((XIAO_AI_NAME, 80.0, XIAO_AI_QUOTES))
        for name, quotes in CHARACTER_QUOTES.items():
            pool.append((name, 1.0, quotes))
        for name, quote in OTHER_CHARACTER_GUIDES:
            pool.append((name, 1.0, [quote]))

    if not pool:
        return XIAO_AI_NAME, rng.choice(XIAO_AI_QUOTES)

    total = sum(item[1] for item in pool)
    pick = rng.uniform(0, total)
    acc = 0.0
    for name, weight, quotes in pool:
        acc += weight
        if pick <= acc:
            return name, rng.choice(quotes)
    name, _, quotes = pool[-1]
    return name, rng.choice(quotes)
